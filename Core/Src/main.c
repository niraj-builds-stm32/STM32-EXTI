// 1. Button interrupt: fires on the button edge
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == GPIO_PIN_13)
  {
    if (!debounce_busy)                    // Only act if we are not already waiting
    {
      debounce_busy = 1;                   // Set the busy flag
      __HAL_TIM_SET_COUNTER(&htim2, 0);    // Reset the timer counter
      HAL_TIM_Base_Start_IT(&htim2);       // Start the 1 ms timer interrupt
    }
  }
}

// 2. Timer interrupt: fires every 1 ms once started
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM2)
  {
    if (debounce_busy)
    {
      static uint8_t tick_count = 0;
      tick_count++;

      if (tick_count >= 20)                // 20 ms have passed
      {
        tick_count = 0;                    // Reset for next time
        HAL_TIM_Base_Stop_IT(&htim2);      // Stop the timer

        // Final check: is the button STILL pressed? (pin is LOW)
        if (HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13) == GPIO_PIN_RESET)
        {
          press_count++;                   // Valid press, count it
        }

        debounce_busy = 0;                 // Free again, ready for the next press
      }
    }
  }
}

